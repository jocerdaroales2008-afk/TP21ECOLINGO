export const STORAGE_KEY = 'ecolingo_clean_points';
export const CUSTOM_STORAGE_KEY = 'ecolingo_custom_points';

export function loadAllPoints(): CleanPoint[] {
  const custom = loadCustomPoints();
  return [...DEFAULT_CLEAN_POINTS, ...custom];
}

export function loadCustomPoints(): CleanPoint[] {
  try {
    const raw = localStorage.getItem(CUSTOM_STORAGE_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw) as CleanPoint[];
    return Array.isArray(parsed) ? parsed : [];
  } catch {
    return [];
  }
}

export function saveCustomPoints(points: CleanPoint[]): void {
  localStorage.setItem(CUSTOM_STORAGE_KEY, JSON.stringify(points));
}

export function addCustomPoint(point: CleanPoint): CleanPoint[] {
  const current = loadCustomPoints();
  const updated = [...current, point];
  saveCustomPoints(updated);
  return updated;
}
